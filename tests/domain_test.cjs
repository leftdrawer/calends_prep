/* No dependencies and no network: exercise actual calendar/constants from app.js. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const context = vm.createContext({console, Date, Intl});
vm.runInContext(source.slice(source.indexOf('const HOLIDAYS'), source.indexOf('/* ── 저장소')), context);
vm.runInContext(source.slice(source.indexOf('const RICE_OFFERINGS'), source.indexOf('function preparationCard')), context);
vm.runInContext(source.slice(source.indexOf('function partLabelOf'), source.indexOf('function renderSheet')), context);
const run = code => vm.runInContext(code, context);
run("idx=LUNAR.findIndex(e=>e[1]===2026&&e[2]===9&&!e[3]);selectedEvent='jungyang'");
assert.equal(run('getSelectedEvent().date'), '2026-10-19');
assert.equal(run('isEventConfigured()'), true);
assert.equal(run('isJungyang()'), true);
assert.equal(run('eventPlan().steps.length'), 0);
assert.equal(run('eventPlan().items.length'), run('GIFTS.length'));
assert.equal(run('JUNGYANG_ANCESTOR.length+JUNGYANG_OFFERINGS.length'), 7);
assert.equal(run('JUNGYANG_OFFERINGS.every(i=>i.id.startsWith("jungyang-rice-offering-"))'), true);
assert.equal(run('RICE_OFFERINGS.every(i=>!i.id.startsWith("jungyang-"))'), true);
assert.equal(run('new Set(JUNGYANG_ANCESTOR.concat(JUNGYANG_OFFERINGS,JUNGYANG_RECOMMENDED,JUNGYANG_PRAYERS).map(i=>i.id)).size'), 13);
assert.equal(run('nameOfKey("part/jungyang-rice-offering-geollip")'), '건립 밥공양 · 재료');
run("selectedEvent='first'");
assert.equal(run('eventPlan().steps.length'), 6);
assert.equal(run('BUY.length'), 18);
assert.equal(run('eventPlan().items.length'), run('ALL.length'));
run("idx=LUNAR.findIndex(e=>e[1]===2026&&e[2]===8&&!e[3]);selectedEvent='chuseok'");
assert.equal(run('isEventConfigured()'), false);
assert.equal(run('eventPlan().items.length'), 0);
run("idx=LUNAR.findIndex(e=>e[1]===2028&&e[2]===5&&e[3]);selectedEvent='first'");
assert.equal(run('eventsFor(LUNAR[idx]).length'), 1);
console.log('PASS: Jungyang date/configuration, 7 basic and 6 separate guide checks, unique event IDs, first-day and unconfigured-holiday preservation.');
